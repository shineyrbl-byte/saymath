export function ui(lang) {
  return { ...UI.en, ...(UI[lang] || {}) };
}

// Puts the interface text for `lang` into the page.
export function applyUI(lang, root = document) {
  const t = { ...UI.en, ...(UI[lang] || {}) };
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = t[el.dataset.i18n];
    if (typeof v === 'string') el.textContent = v;
  });
  // Only our own strings above, never user text, go through innerHTML.
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const v = t[el.dataset.i18nHtml];
    if (typeof v === 'string') el.innerHTML = v;
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      if (typeof t[key] === 'string') el.setAttribute(attr, t[key]);
    }
  });
  if (root === document) {
    document.documentElement.lang = lang;
    document.title = t.pageTitle;
  }
}
